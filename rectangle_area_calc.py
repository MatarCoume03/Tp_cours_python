#Exercise 1 Rectangle Area Calc

print("Veuillez rentrer les dimensions du rectangle pour calculer son aire.")
longueur = float(input("Longueur du rectangle: "))
largeur = float(input("Largeur du rectangle: "))
print("***petit rappel: Aire = longueur x largeur ***")
aire = longueur * largeur
print(f"L'aire du rectangle est de: {longueur} x {largeur} = {aire} m^2")